def para(doc, text, bold=False, size=11, color="242424"):
    p = doc.add_paragraph()
    rtl_paragraph(p)
    paragraph_spacing(p, before=0, after=8, line=1.32)
    add_text(p, text, name=FONT_BODY, size=size, bold=bold, color=color)
    return p


def bullet(doc, text):
    p = doc.add_paragraph(style='List Bullet')
    rtl_paragraph(p, align='right')
    paragraph_spacing(p, before=0, after=5, line=1.28)
    paragraph_indent(p, left=0.9)
    add_text(p, text, name=FONT_BODY, size=10.5, color="242424")
    return p


def finding(doc, title, body, tag="ملاحظة", kind='note'):
    callout(doc, kind, title, [body] if isinstance(body, str) else body)


def matrix_table(doc, rows):
    cols = ["المحتوى", "الموقع الأول", "الموقع الثاني", "نوع العلاقة", "القرار"]
    tbl = doc.add_table(rows=1 + len(rows), cols=len(cols))
    for c, val in enumerate(cols):
        tbl.rows[0].cells[c].text = val
    for r, row in enumerate(rows, start=1):
        for c, val in enumerate(row):
            tbl.rows[r].cells[c].text = val
    style_table_default(tbl, col_widths=[3.6, 3.0, 3.0, 2.8, 3.1], body_size=9.3)
    spacer(doc)
    return tbl


def changelog_table(doc, rows):
    cols = ["#", "التعديل", "الموضع", "السبب / المبرر", "نوع التعديل"]
    tbl = doc.add_table(rows=1 + len(rows), cols=len(cols))
    for c, val in enumerate(cols):
        tbl.rows[0].cells[c].text = val
    for r, row in enumerate(rows, start=1):
        for c, val in enumerate(row):
            tbl.rows[r].cells[c].text = str(row[c])
    style_table_default(tbl, col_widths=[0.7, 4.3, 2.6, 5.0, 2.9], body_size=9.3)
    spacer(doc)
    return tbl


def checklist_table(doc, rows):
    tbl = doc.add_table(rows=len(rows), cols=2)
    set_table_rtl(tbl)
    for r, (status, text) in enumerate(rows):
        c_status, c_text = tbl.rows[r].cells
        write_cell(c_status, "✓" if status else "✗", bold=True,
                   color=WHITE, fill=(GREEN if status else RED), size=12,
                   align='center')
        write_cell(c_text, text, size=10.5, fill=WHITE)
        cell_borders(c_status, color=GRAY_LIGHT, sz=4)
        cell_borders(c_text, color=GRAY_LIGHT, sz=4)
    set_col_widths(tbl, [1.5, 14.0])
    from moh_style import cant_split_table
    cant_split_table(tbl)
    spacer(doc)
    return tbl


